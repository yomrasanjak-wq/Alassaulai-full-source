export type ItineraryMessage = { role: "user" | "assistant"; content: string };

function normalizeArabic(value: string): string {
  return value.normalize("NFKC").replace(/[\u064B-\u065F\u0670\u0640]/g, "").toLowerCase();
}

/** A transparent, non-live itinerary fallback for temporary chat/API outages.
 * It never invents flight times, fares, hotel availability, or opening hours. */
export function buildOfflineItineraryFallback(
  messages: ItineraryMessage[],
  language: "AR" | "TR" | "EN",
): string | undefined {
  if (language !== "AR") return undefined;
  const latest = [...messages].reverse().find((message) => message.role === "user")?.content ?? "";
  const normalized = normalizeArabic(latest);
  const asksPlan = /(?:رتب|رتب لي|رتبلي|خطط|برنامج|جدول|رحله|رحلة|itinerary|travel plan)/i.test(normalized);
  if (!asksPlan) return undefined;

  const hasIstanbul = /(?:اسطنبول|istanbul)/i.test(normalized);
  const hasTrabzon = /(?:طرابزون|ترابزون|trabzon)/i.test(normalized);
  const party = /(?:اربع|أربع|اربعة|أربعة|4)\s*(?:اشخاص|أشخاص|شخص)/i.test(normalized) ? " لأربعة أشخاص" : "";

  if (hasIstanbul && hasTrabzon) {
    return `تعذّر الاتصال بالمساعد مؤقتاً، لكن جهزت لك تصوراً أولياً بحسب ترتيبك${party}: يومان في إسطنبول، ثلاثة أيام في طرابزون، ثم يومان في إسطنبول قبل العودة إلى جدة.

**الأيام 1–2 | إسطنبول**
- اليوم الأول: الوصول من السعودية، تسجيل الدخول والراحة، ثم جولة خفيفة في تقسيم وشارع الاستقلال إذا سمح وقت الوصول.
- اليوم الثاني: السلطان أحمد، آيا صوفيا، الجامع الأزرق، ثم السوق الكبير أو جولة البوسفور.

**الأيام 3–5 | طرابزون**
- اليوم الثالث: رحلة داخلية من إسطنبول إلى طرابزون، ثم ميدان طرابزون وغانيتا وبوزتبه.
- اليوم الرابع: أوزنجول والقرى المحيطة بها، مع وقت كافٍ للتوقف والتصوير.
- اليوم الخامس: دير سوميلا ومتنزه ألتندره، ثم همسي كوي وزيغانا إذا سمح الوقت وحالة الطريق.

**الأيام 6–7 | إسطنبول والعودة**
- اليوم السادس: العودة بالطائرة إلى إسطنبول، ثم وقت للتسوق أو الراحة.
- اليوم السابع: البوسفور أو الجانب الآسيوي، ثم التوجه إلى المطار والعودة إلى جدة وفق موعد الرحلة.

**ترتيب عملي لأربعة أشخاص:** احجزوا تذاكر الذهاب والعودة والرحلة الداخلية بعد تثبيت التواريخ، واختاروا سيارة مع سائق أو سيارة عائلية في طرابزون لتسهيل التنقل بين المرتفعات. لم أضع أسعاراً أو مواعيد طيران لأنها تتغير حسب التاريخ.

هذا برنامج مبدئي وليس حجزاً. أحتاج تاريخ السفر ومدينة المغادرة في السعودية حتى أرتب الرحلات الجوية والتوقيتات بدقة.`;
  }

  if (hasTrabzon) {
    return `تعذّر الاتصال بالمساعد مؤقتاً، لذلك أضع لك برنامجاً مبدئياً لثلاثة أيام في طرابزون:

**اليوم الأول | طرابزون المدينة**
قصر أتاتورك، ميدان طرابزون، ممشى غانيتا على البحر، ثم مطل بوزتبه وقت الغروب.

**اليوم الثاني | أوزنجول والطبيعة**
الانطلاق صباحاً إلى أوزنجول، جولة حول البحيرة والقرية والتوقف في المزارع والمقاهي المطلة، ثم العودة مساءً.

**اليوم الثالث | سوميلا وزيغانا**
دير سوميلا ومتنزه ألتندره الوطني، ثم همسي كوي وزيغانا إذا سمح الوقت وحالة الطريق.

اجعل يوم أوزنجول مستقلاً حتى لا يكون الطريق مرهقاً، واستأجر سيارة أو اتفق مع سائق يعرف طرق المرتفعات. هذا اقتراح عام؛ الطقس وساعات الزيارة والطرق تحتاج إلى التحقق قبل الانطلاق. إذا كانت مدة إقامتك مختلفة أعدّل البرنامج عليها.`;
  }

  return undefined;
}
